import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { format } from "prettier";
import { tokens } from "../design-system/tokens/generated/tokens.ts";

// Email clients cannot consume CSS variables. Serialize only canonical token values.
const paths = {
  canvas: "semantic.color.background.canvas",
  text: "semantic.color.text.primary",
  inset: "semantic.color.surface.inset",
  primary: "component.button.primary.background.default",
  onPrimary: "component.button.primary.content",
  font: "semantic.typography.family.body",
  bodySize: "semantic.typography.body.size",
  bodyLine: "semantic.typography.body.line-height",
  headingSize: "semantic.typography.heading.small-size",
  headingLine: "semantic.typography.heading.small-line-height",
  weight: "semantic.typography.weight.semibold",
  width: "semantic.size.content.form",
  padding: "semantic.space.inset.card-desktop",
  gap: "semantic.space.stack.xl",
  small: "semantic.space.stack.sm",
  buttonPadding: "semantic.space.inline.md",
  radius: "semantic.radius.surface",
  pill: "semantic.radius.pill",
  logo: "semantic.space.stack.xl",
};
const values = Object.fromEntries(
  Object.entries(paths).map(([key, path]) => {
    if (!tokens[path]) throw new Error(`Unknown token: ${path}`);
    return [key, tokens[path].value];
  }),
);
const destination = new URL("../supabase/functions/_shared/chat-email-tokens.ts", import.meta.url);
const serialized = await format(
  `// Generated by scripts/generate-chat-email.mjs; do not edit.\nexport const emailTokens = ${JSON.stringify(values, null, 2)} as const;\n`,
  { parser: "typescript" },
);
if (process.argv.includes("--check")) {
  if ((await readFile(destination, "utf8")).replaceAll("\r\n", "\n") !== serialized) {
    throw new Error("Chat email tokens are stale. Run npm run generate:chat-email.");
  }
} else {
  await writeFile(destination, serialized);
  await sharp(fileURLToPath(new URL("../public/brand/test4test-mark.svg", import.meta.url)), {
    density: 288,
  })
    .resize({ width: 128 })
    .png()
    .toFile(fileURLToPath(new URL("../public/brand/test4test-email-mark.png", import.meta.url)));
}
